impl RecvOpcode {
    pub fn value(self) -> u16 {
        self as u16
    }

    pub fn from_value(v: u16) -> Option<RecvOpcode> {
        match v {
            0x3713 => Some(RecvOpcode::CustomPacket),
            0x01 => Some(RecvOpcode::LoginPassword),
            0x02 => Some(RecvOpcode::GuestLogin),
            0x03 => Some(RecvOpcode::LoginEmail),
            0x04 => Some(RecvOpcode::ServerlistRerequest),
            0x05 => Some(RecvOpcode::CharlistRequest),
            0x06 => Some(RecvOpcode::ServerstatusRequest),
            0x07 => Some(RecvOpcode::AcceptTos),
            0x08 => Some(RecvOpcode::SetGender),
            0x09 => Some(RecvOpcode::AfterLogin),
            0x0A => Some(RecvOpcode::RegisterPin),
            0x0B => Some(RecvOpcode::ServerlistRequest),
            0x0C => Some(RecvOpcode::PlayerDc),
            0x0D => Some(RecvOpcode::ViewAllChar),
            0x0E => Some(RecvOpcode::PickAllChar),
            0x10 => Some(RecvOpcode::NameTransfer),
            0x12 => Some(RecvOpcode::WorldTransfer),
            0x13 => Some(RecvOpcode::CharSelect),
            0x14 => Some(RecvOpcode::PlayerLoggedin),
            0x15 => Some(RecvOpcode::CheckCharName),
            0x16 => Some(RecvOpcode::CreateChar),
            0x17 => Some(RecvOpcode::DeleteChar),
            0x18 => Some(RecvOpcode::Pong),
            _ => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_send_opcode_values() {
        assert_eq!(SendOpcode::LoginStatus.value(), 0x00);
        assert_eq!(SendOpcode::ServerList.value(), 0x0A);
        assert_eq!(SendOpcode::CharList.value(), 0x0B);
        assert_eq!(SendOpcode::ServerIp.value(), 0x0C);
        assert_eq!(SendOpcode::Ping.value(), 0x11);
        assert_eq!(SendOpcode::SetField.value(), 0x7D);
    }

    #[test]
    fn test_recv_from_value() {
        assert_eq!(
            RecvOpcode::from_value(0x01),
            Some(RecvOpcode::LoginPassword)
        );
        assert_eq!(
            RecvOpcode::from_value(0x05),
            Some(RecvOpcode::CharlistRequest)
        );
        assert_eq!(RecvOpcode::from_value(0x13), Some(RecvOpcode::CharSelect));
        assert_eq!(RecvOpcode::from_value(0x18), Some(RecvOpcode::Pong));
        assert_eq!(RecvOpcode::from_value(0x9999), None);
    }
}
